const TABLES: Record<Language, Record<StringKey, string>> = {
  en: STRINGS_EN,
  es: STRINGS_ES,
  fr: STRINGS_FR,
  zh: STRINGS_ZH,
  hi: STRINGS_HI,
  ar: STRINGS_AR,
};

export type InterpolationValues = Record<string, string | number>;

export function translate(
  language: Language,
  key: StringKey,
  values?: InterpolationValues
): string {
  const table = TABLES[language] ?? STRINGS_EN;
  let s = table[key] ?? STRINGS_EN[key] ?? key;
  if (values) {
    for (const [k, v] of Object.entries(values)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}
